"""
Pydantic schemas for the 4-Round Multi-Agent Deliberation and Voting protocol.
Enforces strict JSON structure on LLM outputs at each round boundary.
Includes defensive validators, fuzzy string coercion, action snapping, and audit flags.
"""

from typing import Literal, Optional, Any
from pydantic import BaseModel, Field, ConfigDict, field_validator

StanceType = Literal["withdrawal_of_accommodation", "neutral", "accommodative"]
VALID_ACTIONS_BPS = [-50, -25, 0, 25, 35, 40, 50]


class InitialStanceOutput(BaseModel):
    """Round 1 output: Independent stance formation before seeing colleagues' arguments."""
    model_config = ConfigDict(extra="ignore")

    member_id: str
    member_name: str
    proposed_rate_change_bps: int = Field(
        description="Proposed change to repo rate in basis points: -50, -25, 0, +25, +35, +40, +50"
    )
    proposed_stance: str = Field(
        description="Proposed policy stance: withdrawal_of_accommodation, neutral, accommodative"
    )
    key_rationale: str = Field(
        description="Concise 2-4 sentence macroeconomic reasoning explaining the proposed stance"
    )
    fallback_triggered: bool = Field(
        default=False,
        description="True if this output was generated by defensive heuristic fallback rather than LLM"
    )

    @field_validator("proposed_rate_change_bps", mode="before")
    @classmethod
    def coerce_rate_bps(cls, v: Any) -> int:
        if isinstance(v, str):
            v = v.replace("+", "").replace("bps", "").replace("BPS", "").strip()
        try:
            val = int(round(float(v)))
        except (ValueError, TypeError):
            val = 0
        return min(VALID_ACTIONS_BPS, key=lambda a: abs(a - val))

    @field_validator("proposed_stance", mode="before")
    @classmethod
    def normalize_stance(cls, v: Any) -> str:
        if isinstance(v, str):
            clean = v.lower().strip().replace(" ", "_").replace("-", "_")
            if "accommodat" in clean and "withdrawal" in clean:
                return "withdrawal_of_accommodation"
            if "neutral" in clean:
                return "neutral"
            if "accommodat" in clean:
                return "accommodative"
            return clean
        return str(v)


