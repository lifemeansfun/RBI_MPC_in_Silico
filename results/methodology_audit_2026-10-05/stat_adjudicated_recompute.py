"""Score published predictions under independently adjudicated formal ballot labels.

Depends on data_adjudicated_truth.json generated by the independent data audit.
Never edits the published labels. Reservations and guidance are retained separately.
"""
from pathlib import Path
import hashlib
import json
import pandas as pd

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[1]
truth_path = OUT / "data_adjudicated_truth.json"
truth = json.loads(truth_path.read_text())
mapping = {row["panel_meeting_date"]: row for row in truth["mapping"]}
panel = pd.read_csv(ROOT / "results/tables/meeting_by_meeting_comparison.csv").fillna("")
live = pd.read_csv(ROOT / "results/tables/holdout_meeting_by_meeting_comparison.csv").fillna("")

def ids(value):
    return set(str(value).split(";")) - {"", "nan"}

def met(pred, true):
    tp = sum(len(a & b) for a, b in zip(pred, true))
    fp = sum(len(a - b) for a, b in zip(pred, true))
    fn = sum(len(b - a) for a, b in zip(pred, true))
    return dict(n=len(true),tp=tp,fp=fp,fn=fn, precision=tp/(tp+fp) if tp+fp else None,
        recall=tp/(tp+fn) if tp+fn else None, f1=2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else None,
        exact_match=sum(a==b for a,b in zip(pred,true))/len(true))

all_formal = [set(mapping[d]["strict_rate_stance_dissenters"]) for d in panel.meeting_date]
lag = [set()] + all_formal[:-1]
predictions = {}
metrics_rows = []
for subset in ["all", "calibration", "holdout"]:
    pos = [i for i, row in enumerate(panel.itertuples()) if subset == "all" or row.panel_subset == subset]
    df = panel.iloc[pos]
    true_sets = [all_formal[i] for i in pos]
    metrics_rows += [dict(subset=subset, dimension="union", predictor="saved_mock_panel", **met([ids(v) for v in df.sim_dissenters],true_sets)),
                    dict(subset=subset, dimension="union", predictor="lag_previous_formal_ballot", **met([lag[i] for i in pos],true_sets)),
                    dict(subset=subset, dimension="union", predictor="always_varma", **met([{"jayanth_varma"}]*len(pos),true_sets))]
for dimension, key in [("union","strict_rate_stance_dissenters"),("rate","formal_rate_dissenters"),("stance","formal_stance_dissenters")]:
    pred = []
    true_sets = [set(mapping[d][key]) for d in live.meeting_date]
    for d in live.meeting_date:
        decision=json.loads((ROOT / "runs/holdout_live_run/transcripts" / d / "rep_1/meeting_outcome.json").read_text())
        rate = {v["member_id"] for v in decision["member_votes"] if v["final_rate_vote_bps"] != decision["rate_decision_bps"]}
        stance = {v["member_id"] for v in decision["member_votes"] if v["final_stance_vote"] != decision["stance_decision"]}
        pred.append(rate if dimension=="rate" else stance if dimension=="stance" else rate|stance)
    metrics_rows.append(dict(subset="holdout",dimension=dimension,predictor="saved_live_holdout",**met(pred,true_sets)))
    predictions[dimension]=[dict(date=d,predicted=sorted(p),formal_true=sorted(t)) for d,p,t in zip(live.meeting_date,pred,true_sets)]
df = pd.DataFrame(metrics_rows)
df.to_csv(OUT / "stat_adjudicated_metrics.csv",index=False)
summary = dict(convention=truth["convention"],truth_sha256=hashlib.sha256(truth_path.read_bytes()).hexdigest(),
    metrics=metrics_rows,live_predictions=predictions,
    label_mismatch_dates=[d for d,row in mapping.items() if not row["strict_label_match"]],
    guidance_only_dates=[d for d,row in mapping.items() if row["forward_guidance_dissenters"]])
(OUT / "stat_adjudicated_results.json").write_text(json.dumps(summary,indent=2)+"\n")
print(df.to_string(index=False))
